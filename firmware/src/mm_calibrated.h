static inline uint32_t mmc_u7(int32_t v) { return v < 0 ? 0u : v > 127 ? 127u : (uint32_t)v; }
static inline int32_t mmc_limit(int64_t v, int32_t lo, int32_t hi)
{
    return v < lo ? lo : v > hi ? hi : (int32_t)v;
}
/* Keep wide products out of line and consume them before returning: the target
 * CPU can corrupt a multiply issued beside a load. Target disassembly still needs
 * a multiply/load hazard scan; a successful host test or link cannot prove this. */
static __attribute__((noinline)) int64_t mmc_mul64(int32_t a, int32_t b, uint32_t shift)
{
    return ((int64_t)a * b) >> shift;
}
static __attribute__((noinline)) uint32_t mmc_umul(uint32_t a, uint32_t b, uint32_t shift)
{
    return (uint32_t)(((uint64_t)a * b) >> shift);
}
static __attribute__((noinline)) uint64_t mmc_dot_x4(int32_t a, int32_t b, int32_t c, int32_t d)
{
    return (uint64_t)((int64_t)a * b + (int64_t)c * d) << 2;
}
static inline int64_t mmc_dot(int32_t a, int32_t b, int32_t c, int32_t d)
{
    return (int64_t)mmc_dot_x4(a, b, c, d) >> 2;
}
static inline int32_t mmc_mul(int32_t a, int32_t b, uint32_t shift)
{
    return (int32_t)mmc_mul64(a, b, shift);
}
/* Reciprocal refined with multiplies: retains damping at low cutoff and high Q,
 * without requiring a target runtime helper for 64-bit division. */
static void mmc_svf_set(mmc_svf_t *f, uint32_t g, uint32_t k)
{
    int32_t den = (1 << 24) + mmc_mul((int32_t)g, (int32_t)(g + k), 24);
    int32_t a1 = (int32_t)((0x80000000u / (uint32_t)(den >> 10)) << 13);
    int32_t e = (1 << 30) + mmc_mul(-den, a1, 24);
    a1 += mmc_mul(a1, e, 30);
    f->a1 = a1;
    f->a2 = mmc_mul((int32_t)g, a1, 24);
    f->a3 = mmc_mul((int32_t)g, f->a2, 24);
    f->k = (int32_t)k;
}
/* Input bounded to +/-2^26 by mmc_chain_tick; states to +/-2^28. */
static inline void mmc_svf_tick(mmc_svf_t *f, int32_t x, int32_t *lp, int32_t *bp, int32_t *hp)
{
    int32_t v3 = x - f->s2;
    int64_t p1 = mmc_dot(f->a1, f->s1, f->a2, v3) + f->r1;
    int64_t p2 = mmc_dot(f->a2, f->s1, f->a3, v3) + f->r2;
    int32_t v1 = (int32_t)(p1 >> 30), v2 = f->s2 + (int32_t)(p2 >> 30);
    f->r1 = (uint32_t)p1 & ((1u << 30) - 1);
    f->r2 = (uint32_t)p2 & ((1u << 30) - 1);
    f->s1 = mmc_limit(2LL * v1 - f->s1, -MMC_STATE_MAX, MMC_STATE_MAX);
    f->s2 = mmc_limit(2LL * v2 - f->s2, -MMC_STATE_MAX, MMC_STATE_MAX);
    if (lp) *lp = v2;
    if (bp) *bp = v1;
    if (hp) *hp = mmc_limit((int64_t)x - mmc_mul64(f->k, v1, 24) - v2,
                           -MMC_STATE_MAX, MMC_STATE_MAX);
}
static inline int32_t mmc_op_lp(mmc_op_t *f, int32_t x)
{
    int64_t p = mmc_mul64(x - f->s, f->g, 0) + f->r;
    int32_t v = (int32_t)(p >> 24), y = f->s + v;
    f->r = (uint32_t)p & ((1u << 24) - 1);
    f->s = mmc_limit((int64_t)y + v, -MMC_STATE_MAX, MMC_STATE_MAX);
    return y;
}
/* Position: 1/96 octave above MIDI note 0, Q8. */
static uint32_t mmc_fg_at(const uint32_t *table, int32_t pos)
{
    uint32_t i;
    if (pos <= 0) return table[0];
    i = (uint32_t)pos >> 8;
    if (i >= MMC_FILTER_TOP) return table[MMC_FILTER_TOP];
    return table[i] + (((table[i + 1] - table[i]) * ((uint32_t)pos & 255u)) >> 8);
}
/* hp/lp positions already include note, BASE/WIDTH and envelope offsets. */
static void mmc_chain_set(mmc_chain_t *f, int32_t hp_pos, int32_t lp_pos,
                          int32_t hpq, int32_t lpq, int32_t eqf, int32_t eqg)
{
    uint32_t h = mmc_u7(hpq), l = mmc_u7(lpq), e = mmc_u7(eqg);
    mmc_svf_set(&f->lp, mmc_fg_at(mmc_fg, lp_pos + mmc_lpc[l]), mmc_lpk[l]);
    mmc_svf_set(&f->hp, mmc_fg_at(mmc_fg, hp_pos + mmc_hpc[h]), mmc_hpk[h]);
    f->lp2a.g = f->lp2b.g = (int32_t)mmc_fg_at(mmc_fg1, lp_pos + MMC_LP2_OFFSET * 256);
    f->hp1.g = (int32_t)mmc_fg_at(mmc_fg1, hp_pos + MMC_HP1_OFFSET * 256);
    f->eq_on = e != 64u;
    if (f->eq_on) {
        uint32_t gain = mmc_eqgain[e];
        uint32_t k = e > 64u ? MMC_EQ_K : mmc_umul(MMC_EQ_K, gain, 16);
        int32_t c = mmc_mul((int32_t)gain - 65536, MMC_EQ_K, 16);
        mmc_svf_set(&f->eq, mmc_eqg[mmc_u7(eqf)], k);
        f->eqc = e > 64u ? c : -c;
    }
}
/* Machine ceiling multiplier Q12: sine/SID/dynamic FM/noise 4096;
 * stat FM/voice -1.4 dB, saw -10.5, ensemble +1.7, wave -7,
 * parallel FM +0.3, pulse -2.75. Calibrate machine output before choosing it. */
static int32_t mmc_dist_ceiling(int32_t value, uint32_t machine_q12)
{
    return mmc_limit(mmc_mul64(mmc_dist_c[mmc_u7(value)], (int32_t)machine_q12, 12), 1, 1 << 24);
}
/* x: machine sample in signed 16-bit units; output before AMP.
 * Headroom shift defaults to 24; donor noise/ring machines use 22/23. */
static int32_t mmc_chain_tick(mmc_chain_t *f, int32_t x, uint32_t gain_q24, uint32_t shift, int32_t ceiling)
{
    int32_t band, y;
    x = mmc_limit(mmc_mul64(x, (int32_t)gain_q24, shift), -(1 << 24), 1 << 24);
    if (f->eq_on) {
        mmc_svf_tick(&f->eq, x, 0, &band, 0);
        x = mmc_limit((int64_t)x + mmc_mul64(band, f->eqc, 24), -(1 << 26), 1 << 26);
    }
    mmc_svf_tick(&f->lp, x, &y, 0, 0);
    x = mmc_limit(y, -ceiling, ceiling);
    mmc_svf_tick(&f->hp, x, 0, 0, &y);
    f->hp.s1 = mmc_limit(f->hp.s1, -ceiling, ceiling);
    f->hp.s2 = mmc_limit(f->hp.s2, -ceiling, ceiling);
    y -= mmc_op_lp(&f->hp1, y);
    return mmc_op_lp(&f->lp2b, mmc_op_lp(&f->lp2a, y));
}
static inline uint32_t mmc_hold_samples(int32_t value, uint32_t bpm)
{
    uint32_t v = mmc_u7(value);
    if (v == 127u) return UINT32_MAX;
    if (!bpm) bpm = 1;
    if (bpm > 1000u) bpm = 1000u;
    return (v * (MMC_RATE * 60u) + bpm * 16u) / (bpm * 32u);
}
static inline void mmc_amp_trigger(mmc_amp_t *a, int32_t attack)
{
    if (mmc_u7(attack) == 0u) a->level = 0;
    a->gate = 1;
    a->let_go = 0;
    a->hold = 0;
    a->stage = MMC_ENV_ATTACK;
}
static inline void mmc_amp_release(mmc_amp_t *a)
{
    a->gate = 0;
    a->let_go = 1;
}
static inline void mmc_amp_gate_end(mmc_amp_t *a) { a->gate = 0; }
/* Explicit note-off ends HOLD/DEC; an attack already underway finishes first.
 * Timed gate expiry leaves finite HOLD/DEC running; gated 127 settings release. */
static inline uint32_t mmc_amp_tick(mmc_amp_t *a, int32_t attack, int32_t hold,
                                    int32_t decay, int32_t release, uint32_t bpm)
{
    switch (a->stage) {
    case MMC_ENV_ATTACK:
        a->level += mmc_amp_attack[mmc_u7(attack)];
        if (a->level >= MMC_ENV_ONE) {
            a->level = MMC_ENV_ONE;
            a->hold = mmc_hold_samples(hold, bpm);
            a->stage = a->hold ? MMC_ENV_HOLD : MMC_ENV_DECAY;
        }
        break;
    case MMC_ENV_HOLD:
        if (a->let_go || (a->hold == UINT32_MAX && !a->gate)) a->stage = MMC_ENV_RELEASE;
        else if (a->hold != UINT32_MAX && (!a->hold || !--a->hold)) a->stage = MMC_ENV_DECAY;
        break;
    case MMC_ENV_DECAY:
        if (a->let_go) { a->stage = MMC_ENV_RELEASE; break; }
        if (mmc_u7(decay) == 127u) {
            if (!a->gate) a->stage = MMC_ENV_RELEASE;
            break;
        }
        a->level = mmc_umul(a->level, mmc_amp_decay[mmc_u7(decay)], 31);
        if (a->level < (1u << 15)) a->level = a->stage = 0;
        break;
    case MMC_ENV_RELEASE:
        a->level = mmc_umul(a->level, mmc_amp_decay[mmc_u7(release)], 31);
        if (a->level < (1u << 15)) a->level = a->stage = 0;
        break;
    default: a->level = 0; break;
    }
    return a->level;
}
static inline void mmc_filter_trigger(mmc_filter_env_t *e) { e->level = 0; e->attack = 1; }
static inline uint32_t mmc_filter_tick(mmc_filter_env_t *e, int32_t attack, int32_t decay)
{
    if (e->attack) {
        e->level += mmc_filter_attack[mmc_u7(attack)];
        if (e->level >= MMC_ENV_ONE) { e->level = MMC_ENV_ONE; e->attack = 0; }
    } else {
        uint32_t d = mmc_filter_decay[mmc_u7(decay)];
        e->level = e->level > d ? e->level - d : 0;
    }
    return e->level;
}
/* Signed BOFS/WOFS -64..63, output filter steps Q8 at envelope level Q30. */
static inline int32_t mmc_filter_offset(int32_t value, uint32_t level)
{
    int32_t v = value < -64 ? -64 : value > 63 ? 63 : value;
    return mmc_mul(7 * v * (v < 0 ? -v : v), (int32_t)level, 30);
}
static inline int32_t mmc_srr_tick(mmc_srr_t *s, int32_t x, int32_t value)
{
    uint32_t v = mmc_u7(value);
    if (!v) { s->held = s->previous = x; s->phase = 0; return x; }
    s->phase += mmc_srr_inc[v];
    if (s->phase >= 65536u) { s->phase -= 65536u; s->previous = s->held; s->held = x; }
    return s->previous + mmc_mul(s->held - s->previous, (int32_t)s->phase, 16);
}
