static inline int32_t mml_sine(uint32_t phase)
{
    uint32_t i=phase>>22, f=(phase>>6)&65535u;
    int32_t a=mml_sin_table[i], b=mml_sin_table[i+1];
    return a+(((b-a)*(int32_t)f)>>16);
}
#define MML_SIN mml_sine
#endif
typedef struct {
    uint32_t phase;
    int32_t value, hold, random;
    uint8_t done;
} mml_voice;
typedef struct { uint8_t track, param; int32_t value; } mml_mod;
typedef struct {
    mml_voice voice[MML_TRACKS][MML_LFOS];
    mml_mod mod[MML_MAX_MOD];
    uint8_t count;
} mml_state;
static inline void mml_init(mml_state *s) { memset(s,0,sizeof(*s)); }
static inline int32_t mml_delta(const mml_state *s, unsigned track, unsigned param)
{
    for(unsigned i=0;i<s->count;++i)
        if(s->mod[i].track==track && s->mod[i].param==param) return s->mod[i].value;
    return 0;
}
static inline int32_t mml_shape(unsigned wave, uint32_t phase, int32_t random)
{
    int32_t x=(int32_t)(phase>>16);
    switch(wave) {
    case 0: return x<32768 ? x*2-32768 : (65535-x)*2-32768;
    case 1: return MML_SIN(phase);
    case 2: return phase<0x80000000u ? 32767 : -32767;
    case 3: return 32767-x;
    case 4: { uint32_t y=65535u-(uint32_t)x; y=(y*y)>>16; y=(y*y)>>16; return (int32_t)(y>>1); }
    case 5: return x>>1;
    default: return random;
    }
}
static inline uint32_t mml_random(uint32_t *rng)
{
    *rng ^= *rng<<13; *rng ^= *rng>>17; *rng ^= *rng<<5;
    return *rng;
}
/* raw controls must be 0..127; trigger applies to one track's three LFOs.
 * FREE continues, TRIG/ONE/HALF reset to PHASE, HOLD samples current waveform.
 * A skipped source LFO trigger means the caller simply omits this call. */
static inline void mml_trigger(mml_state *s, unsigned track, const uint8_t raw[3][8])
{
    if(track>=MML_TRACKS) return;
    for(unsigned l=0;l<MML_LFOS;++l) {
        mml_voice *v=&s->voice[track][l];
        unsigned trig=(raw[l][MML_TRIG]*5u)>>7;
        if(!trig) continue;
        if(trig==2) { v->hold=mml_shape((raw[l][MML_WAVE]*7u)>>7,v->phase,v->random); continue; }
        v->phase=(uint32_t)raw[l][MML_PHASE]<<25;
        v->done=0;
    }
}
static inline int mml_control(const mml_state *s, unsigned t, unsigned l, unsigned p, uint8_t raw)
{
    int32_t q=(int32_t)raw*256+mml_delta(s,t,42+l*8+p);
    return q<0 ? 0 : q>127*256 ? 127 : q>>8;
}
/* All tracks must be evaluated together, preserving one-block cross modulation.
 * bpm10 is tempo in tenths of BPM (1200 = 120 BPM); unsigned arithmetic wraps
 * exactly like the donor at extreme speed/multiplier/tempo. view_track selects
 * the waveform monitor even at zero depth; use -1 when no monitor is needed.
 * Output s->mod[0..count) replaces the previous output, never accumulates stale
 * destinations. Trigger before this call when the sequencer triggers a note. */
static inline void mml_block(mml_state *s, const uint8_t raw[6][3][8],
                             uint32_t bpm10, uint32_t *rng, int view_track)
{
    mml_mod next[MML_MAX_MOD];
    unsigned count=0;
    for(unsigned t=0;t<MML_TRACKS;++t) for(unsigned l=0;l<MML_LFOS;++l) {
        mml_voice *v=&s->voice[t][l];
        int dest=mml_control(s,t,l,MML_DEST,raw[t][l][MML_DEST]);
        if(dest==0 || dest>MML_PARAMS) { v->value=0; continue; }
        unsigned wave=(mml_control(s,t,l,MML_WAVE,raw[t][l][MML_WAVE])*7u)>>7;
        unsigned trig=(mml_control(s,t,l,MML_TRIG,raw[t][l][MML_TRIG])*5u)>>7;
        unsigned mult=1u<<((mml_control(s,t,l,MML_MULT,raw[t][l][MML_MULT])*8u)>>7);
        uint32_t inc=(uint32_t)mml_control(s,t,l,MML_SPEED,raw[t][l][MML_SPEED])*mult*bpm10*10u;
        uint32_t before=v->phase;
        if(!v->done) {
            v->phase+=inc;
            if(v->phase<before) v->random=(int32_t)(mml_random(rng)>>16)-32768;
            if(trig>=3) {
                uint32_t start=(uint32_t)raw[t][l][MML_PHASE]<<25;
                uint32_t a=before-start, z=v->phase-start;
                if(trig==3 && z<a) {v->done=1;v->phase=start-1u;}
                if(trig==4 && z>=0x80000000u && a<0x80000000u) {v->done=1;v->phase=start+0x80000000u;}
            }
        }
        int depth=mml_control(s,t,l,MML_DEPTH,raw[t][l][MML_DEPTH])-64;
        if(!depth && (int)t!=view_track) {v->value=0;continue;}
        v->value=trig==2 ? v->hold : mml_shape(wave,v->phase,v->random);
        if(depth) {
            unsigned target=(mml_control(s,t,l,MML_TARGET,raw[t][l][MML_TARGET])*6u)>>7;
            unsigned param=mml_destination[dest], i=0;
            int32_t value=(v->value*depth)>>6;
            for(;i<count;++i) if(next[i].track==target && next[i].param==param) break;
            if(i==count) next[count++]=(mml_mod){(uint8_t)target,(uint8_t)param,0};
            next[i].value+=value;
        }
    }
    for(unsigned i=0;i<count;++i) s->mod[i]=next[i];
    s->count=(uint8_t)count;
}
