static inline int32_t mmb_adpcm_step(mmb_crunch_t *s, int c, int32_t x)
{
    int32_t step = mmb_t_adpcm_step[s->ad_idx[c]], diff = x - s->ad_pred[c];
    int code = 0;
    if (diff < 0) { code = 8; diff = -diff; }
    int32_t delta = step >> 3;
    if (diff >= step) { code |= 4; diff -= step; delta += step; }
    step >>= 1;
    if (diff >= step) { code |= 2; diff -= step; delta += step; }
    step >>= 1;
    if (diff >= step) { code |= 1; delta += step; }
    s->ad_pred[c] = mm2_sat16(s->ad_pred[c] + ((code & 8) ? -delta : delta));
    s->ad_idx[c] = MM2_CLAMP(s->ad_idx[c] + mmb_adpcm_idx[code & 7], 0, 88);
    return s->ad_pred[c];
}

static void mmb_reverb_block(mmb_reverb_t *s, unsigned verb, unsigned damping, const int32_t rsend[16], int32_t L[16], int32_t R[16]) {
 if(!verb || !s->buffer)return; verb=verb>127?127:verb; damping=damping>127?127:damping;
        int32_t fb = 22938 + verb * 72;
        int32_t damp = mmb_t_op_h[127 - damping];
        for (int i = 0; i < MM2_BLOCK; i += 2) {
            int32_t x = (rsend[i] + rsend[i + 1]) >> 2;
            int32_t sum = 0, off = 0;
            for (int c = 0; c < 4; c++) {
                int16_t *b = &s->buffer[off];
                int32_t y = b[s->cb_pos[c]];
                
                int32_t q = (y - s->cb_lp[c]) * damp + s->cb_r[c];
                s->cb_lp[c] += q >> 15;
                s->cb_r[c] = q & 32767;
                int32_t v = s->cb_lp[c] * fb;
                b[s->cb_pos[c]] = (int16_t)mm2_sat16(x + ((v + (v < 0 ? 32767 : 0)) >> 15));
                if (++s->cb_pos[c] >= mmb_cb_len[c]) s->cb_pos[c] = 0;
                sum += y;
                off += mmb_cb_len[c];
            }
            int32_t ch[2] = {sum, sum};                   
            off = 0;
            for (int a = 0; a < 4; a++) {
                int16_t *b = &(s->buffer + 2468)[off];
                int c = a >> 1;
                int32_t d = b[s->ap_pos[a]];
                int32_t v = ch[c] + (d >> 1);
                b[s->ap_pos[a]] = (int16_t)mm2_sat16(v);
                ch[c] = d - (v >> 1);
                if (++s->ap_pos[a] >= mmb_ap_len[a]) s->ap_pos[a] = 0;
                off += mmb_ap_len[a];
            }
            s->rv_l = ch[0];
            s->rv_r = ch[1];
            L[i] += s->rv_l; R[i] += s->rv_r;
            L[i + 1] += s->rv_l; R[i + 1] += s->rv_r;
        }
}
static void mmb_tape_block(mmb_tape_t *s, unsigned amount, int32_t L[16], int32_t R[16]) {
 if(!amount || !s->buffer)return; amount=amount>127?127:amount;
 int32_t tq=mmb_t_tape_q8[amount];
 const uint32_t wow_inc=54000,flut_inc=620000;
 for(unsigned i=0;i<16;i++) { int32_t l=L[i],r=R[i];
            s->buffer[s->tw & 2047][0] = (int16_t)mm2_sat16(l);
            s->buffer[s->tw & 2047][1] = (int16_t)mm2_sat16(r);
            s->wow += wow_inc;
            s->flut += flut_inc;
            
            int32_t m = (mm2_sinp(s->wow) * 48 + mm2_sinp(s->flut)) >> 6;           
            int32_t d = (420 << 8) + (int32_t)mm2_mul_sh(m, tq * 3, 15);         
            uint32_t pos = (s->tw << 8) - (uint32_t)d;                       
            uint32_t j = pos >> 8;
            int32_t f = (int32_t)(pos & 255);
            int32_t tl = (s->buffer[j & 2047][0] * (256 - f) + s->buffer[(j + 1) & 2047][0] * f) >> 8;
            int32_t tr = (s->buffer[j & 2047][1] * (256 - f) + s->buffer[(j + 1) & 2047][1] * f) >> 8;
            s->tw++;
            int32_t li = 127 * 1024 - tq, lj = li >> 10;                     
            int32_t a = mm2_t_op[lj] + (((mm2_t_op[lj < 127 ? lj + 1 : 127] - mm2_t_op[lj]) * (li & 1023)) >> 10);
            s->tlp_l += ((tl - s->tlp_l) * a) >> 15;
            s->tlp_r += ((tr - s->tlp_r) * a) >> 15;
            l = s->tlp_l;
            r = s->tlp_r;
 L[i]=l;R[i]=r;
 }
}
static void mmb_crunch_block(mmb_crunch_t *s, unsigned amount, int32_t L[16], int32_t R[16]) {
 if(!amount)return; amount=amount>127?127:amount;
 int32_t ad_mix=amount*2>127?127:(int32_t)amount*2,ad_div=mmb_t_adpc_div[amount];
 for(unsigned i=0;i<16;i++) { int32_t l=L[i],r=R[i];
            s->ad_acc += 256;
            if (s->ad_acc >= ad_div) {
                s->ad_acc -= (uint16_t)ad_div;
                s->ad_hold[0] = mmb_adpcm_step(s,0, mm2_sat16(l));
                s->ad_hold[1] = mmb_adpcm_step(s,1, mm2_sat16(r));
            }
            l += ((s->ad_hold[0] - l) * ad_mix) >> 7;
            r += ((s->ad_hold[1] - r) * ad_mix) >> 7;
 L[i]=l;R[i]=r;
 }
}
static void mmb_hiss_block(mmb_hiss_t *s, unsigned hiss, int rolling, int32_t L[16], int32_t R[16]) {
 hiss=hiss>127?127:hiss;
 int32_t hgain=s->hgain,htgt=rolling?32767:0;
 for(unsigned i=0;i<16;i++) { int32_t l=L[i],r=R[i];
        hgain += (htgt - hgain) >> 13;
        if (hiss && hgain > 64) {
            int32_t n = (int32_t)mm2_noise_step(&s->hs) >> 16;
            s->hlp += ((n - s->hlp) * 9000) >> 15;
            int32_t h = (s->hlp * mmb_t_hiss_g[hiss]) >> 15;       
            
            uint32_t cr = ((s->hs & 0x3FFFF) << 3) | ((s->hs >> 18) & 7);
            if (cr < mmb_t_crk_p[hiss] && !s->crackle) s->crackle = (int32_t)(1500 + (s->hs >> 21)) * mmb_t_crk_a[hiss] >> 10;
            if (s->crackle) { h += (s->hs & 0x100000) ? s->crackle : -s->crackle; s->crackle = (s->crackle * 5) >> 3; if (s->crackle < 100) s->crackle = 0; }
            h = (h * hgain) >> 15;
            l += h;
            r += h;
        }
 L[i]=l;R[i]=r;
 } s->hgain=hgain;
}
static inline int32_t mmb_limit(int32_t x)
{
    if ((uint32_t)x + 17407u <= 17407u + 16384u) return x;   
    if (x >= 131071) return 32767;
    if (x <= -131071) return -32767;
    int32_t u = x + 131072, i = u >> 10, f = u & 1023;
    return mmb_t_lim[i] + (((mmb_t_lim[i + 1] - mmb_t_lim[i]) * f) >> 10);
}

/* Same shared bus drive/master law; apply once, after the desired stages. */
static void mmb_drive_block(unsigned drive,unsigned volume,const int32_t L[16],const int32_t R[16],int16_t out[32]) {
 drive=drive>127?127:drive;volume=volume>127?127:volume;
 int32_t drv=mmb_t_driv[drive],mvol=mmb_t_mvol[volume];
 for(unsigned i=0;i<16;i++) {
  uint64_t lr=mm2_mul2_q15(mvol,(L[i]*drv)>>8,(R[i]*drv)>>8);
  out[2*i]=(int16_t)mmb_limit((int32_t)lr);
  out[2*i+1]=(int16_t)mmb_limit((int32_t)(lr>>32));
 }
}
